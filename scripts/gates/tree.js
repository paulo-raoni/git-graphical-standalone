import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Walking the **working tree**, which is not the same set of files as the index.
 *
 * `AGENTS.md` §10 records the trap this exists to avoid: `git grep` searches
 * tracked files only, so a grep gate run over new files before they are staged
 * prints nothing — including for the file that would have failed it. Every gate
 * that asks "is there anything wrong in the tree" therefore reads the tree, with
 * `readdir`, and ignores git's opinion of what is in it.
 */

/** The repository root, two directories above this file. */
export const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/**
 * Directories no gate reads.
 *
 * Everything here is either not ours (`node_modules`), git's own storage, or
 * generated by a gate — including the fixture repositories, which are real git
 * repositories full of objects and would otherwise be searched byte by byte.
 */
export const GENERATED = [
  '.git',
  'node_modules',
  'dist',
  'coverage',
  'reports',
  'test-results',
  'playwright-report',
  '.stryker-tmp',
  join('test', 'fixtures', 'repositories'),
];

function isSkipped(relativePath, skipped) {
  return skipped.some(
    (entry) => relativePath === entry || relativePath.startsWith(`${entry}${'/'}`),
  );
}

/**
 * Every file under `root`, as paths relative to it, with `/` separators so that
 * a gate's message reads the same on every platform.
 */
export function walkFiles(root = repositoryRoot, skipped = GENERATED) {
  const found = [];
  const pending = [''];
  while (pending.length > 0) {
    const directory = pending.pop() ?? '';
    for (const entry of readdirSync(join(root, directory), { withFileTypes: true })) {
      const here = directory === '' ? entry.name : `${directory}/${entry.name}`;
      const native = relative(root, join(root, here)).split('\\').join('/');
      if (
        isSkipped(
          native,
          skipped.map((one) => one.split('\\').join('/')),
        )
      ) {
        continue;
      }
      if (entry.isDirectory()) {
        pending.push(here);
      } else if (entry.isFile()) {
        found.push(here);
      }
    }
  }
  return found.sort();
}

/**
 * The file's text, or `null` when it is not text.
 *
 * A zero byte is the test, which is what every other tool uses and is right
 * about everything this repository will ever hold.
 */
export function readText(root, relativePath) {
  const bytes = readFileSync(join(root, relativePath));
  if (bytes.includes(0)) {
    return null;
  }
  return bytes.toString('utf8');
}

/** Report a gate's findings and set the exit status. One shape for every gate. */
export function report(gate, findings) {
  if (findings.length === 0) {
    process.stdout.write(`${gate}: ok\n`);
    return;
  }
  process.stderr.write(`${gate}: ${String(findings.length)} finding(s)\n`);
  for (const finding of findings) {
    process.stderr.write(`  ${finding}\n`);
  }
  process.exitCode = 1;
}
